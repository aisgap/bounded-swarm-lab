import { index, integer, sqliteTable, text, uniqueIndex } from "drizzle-orm/sqlite-core";

export const runs = sqliteTable(
  "runs",
  {
    id: text("id").primaryKey(),
    userId: text("user_id").notNull(),
    idempotencyKey: text("idempotency_key").notNull(),
    mode: text("mode").notNull(),
    objective: text("objective").notNull(),
    acceptanceCriteria: text("acceptance_criteria").notNull(),
    model: text("model").notNull(),
    priceVersion: text("price_version").notNull(),
    status: text("status").notNull(),
    currentAgent: text("current_agent").notNull(),
    callCount: integer("call_count").notNull().default(0),
    handoffCount: integer("handoff_count").notNull().default(0),
    researcherVisits: integer("researcher_visits").notNull().default(0),
    architectVisits: integer("architect_visits").notNull().default(0),
    coderVisits: integer("coder_visits").notNull().default(0),
    reviewerVisits: integer("reviewer_visits").notNull().default(0),
    maxCalls: integer("max_calls").notNull(),
    maxHandoffs: integer("max_handoffs").notNull(),
    maxVisitsPerAgent: integer("max_visits_per_agent").notNull(),
    tokenBudget: integer("token_budget").notNull(),
    maxInputTokens: integer("max_input_tokens").notNull(),
    maxOutputTokens: integer("max_output_tokens").notNull(),
    runSpendCapMicrousd: integer("run_spend_cap_microusd").notNull(),
    reservedTokens: integer("reserved_tokens").notNull().default(0),
    usedTokens: integer("used_tokens").notNull().default(0),
    outstandingMicrousd: integer("outstanding_microusd").notNull().default(0),
    reconciledMicrousd: integer("reconciled_microusd").notNull().default(0),
    activeStepId: text("active_step_id"),
    stopRequested: integer("stop_requested", { mode: "boolean" }).notNull().default(false),
    version: integer("version").notNull().default(0),
    deadlineAt: integer("deadline_at").notNull(),
    lastErrorCode: text("last_error_code"),
    createdAt: integer("created_at").notNull(),
    updatedAt: integer("updated_at").notNull(),
  },
  (table) => [
    uniqueIndex("runs_user_idempotency_unique").on(table.userId, table.idempotencyKey),
    index("runs_user_created_idx").on(table.userId, table.createdAt),
  ],
);

export const steps = sqliteTable(
  "steps",
  {
    id: text("id").primaryKey(),
    runId: text("run_id").notNull().references(() => runs.id, { onDelete: "cascade" }),
    userId: text("user_id").notNull(),
    stepNumber: integer("step_number").notNull(),
    idempotencyKey: text("idempotency_key").notNull(),
    agent: text("agent").notNull(),
    status: text("status").notNull(),
    nextAgent: text("next_agent"),
    clientRequestId: text("client_request_id").notNull(),
    providerRequestId: text("provider_request_id"),
    providerResponseId: text("provider_response_id"),
    reservedInputTokens: integer("reserved_input_tokens").notNull(),
    reservedOutputTokens: integer("reserved_output_tokens").notNull(),
    reservedMicrousd: integer("reserved_microusd").notNull(),
    inputTokens: integer("input_tokens"),
    cachedInputTokens: integer("cached_input_tokens"),
    cacheWriteTokens: integer("cache_write_tokens"),
    outputTokens: integer("output_tokens"),
    reasoningTokens: integer("reasoning_tokens"),
    totalTokens: integer("total_tokens"),
    actualMicrousd: integer("actual_microusd"),
    safeErrorCode: text("safe_error_code"),
    retryAfterSeconds: integer("retry_after_seconds"),
    startedAt: integer("started_at").notNull(),
    completedAt: integer("completed_at"),
  },
  (table) => [
    uniqueIndex("steps_run_number_unique").on(table.runId, table.stepNumber),
    uniqueIndex("steps_run_idempotency_unique").on(table.runId, table.idempotencyKey),
    index("steps_run_started_idx").on(table.runId, table.startedAt),
  ],
);

export const records = sqliteTable(
  "records",
  {
    id: text("id").primaryKey(),
    runId: text("run_id").notNull().references(() => runs.id, { onDelete: "cascade" }),
    stepId: text("step_id").notNull().references(() => steps.id, { onDelete: "cascade" }),
    sequence: integer("sequence").notNull(),
    author: text("author").notNull(),
    contentJson: text("content_json").notNull(),
    createdAt: integer("created_at").notNull(),
  },
  (table) => [uniqueIndex("records_run_sequence_unique").on(table.runId, table.sequence)],
);

export const experimentBudget = sqliteTable("experiment_budget", {
  id: text("id").primaryKey(),
  authorizedMicrousd: integer("authorized_microusd").notNull(),
  startThresholdMicrousd: integer("start_threshold_microusd").notNull(),
  outstandingMicrousd: integer("outstanding_microusd").notNull().default(0),
  reconciledMicrousd: integer("reconciled_microusd").notNull().default(0),
  activeStepId: text("active_step_id"),
  leaseExpiresAt: integer("lease_expires_at"),
  version: integer("version").notNull().default(0),
  updatedAt: integer("updated_at").notNull(),
});

export const auditEvents = sqliteTable(
  "audit_events",
  {
    id: text("id").primaryKey(),
    userId: text("user_id").notNull(),
    runId: text("run_id"),
    stepId: text("step_id"),
    eventType: text("event_type").notNull(),
    safeMetadataJson: text("safe_metadata_json").notNull(),
    createdAt: integer("created_at").notNull(),
  },
  (table) => [index("audit_run_created_idx").on(table.runId, table.createdAt)],
);
